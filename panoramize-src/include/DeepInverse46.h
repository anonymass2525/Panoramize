#pragma once
// Panoramize 4.6 offline inverse instrument research pipeline.
// Estimates descriptors and *candidate* techniques, then searches constrained
// physical families. Does not claim unique geometric/material identification.
#include "PerformancePhysical30.h"
#include "ShapeInverse37.h"
#include "GenerativePhysics37.h"
#include <array>
#include <string>
#include <vector>
namespace panorama::deep46 {
struct Frame {
 double seconds=0, rms=0, centroidHz=0, brightness=0, flatness=0;
 double pitchHz=0,pitchConfidence=0;
};
struct Section {
 double fromSec=0,toSec=0;
 double rms=0,centroidHz=0,brightness=0;
};
struct Gesture {
 enum class Kind { Attack, LegatoCandidate, VibratoCandidate, DampingChange, PitchChange };
 Kind kind=Kind::Attack;double timeSec=0,confidence=0,magnitude=0,rateHz=0;
};
struct Analysis {
 int sampleRate=0;double durationSec=0;
 std::vector<Frame> frames;
 std::vector<Section> sections;
 std::vector<Gesture> gestures;
 double centroidChange=0,validPitchFraction=0;
 std::string error;
};
Analysis analyze(const std::vector<float>& mono,int rate,int hop=256);
const char* gestureName(Gesture::Kind) noexcept;

struct WaveCandidate {
 gen37::WaveRecipe model;
 double trainingLoss=1e30,holdoutLoss=1e30;
};
struct WaveFit {
 std::vector<WaveCandidate> proposals;
 int evaluations=0;
 double ambiguityRatio=0;
 std::string error;
};
// Limited wave structure, material surrogate (frequency/damping), excitation
// position search. `pickup` is known to prevent a blind inverse ambiguity.
WaveFit fitWave(const std::vector<float>&train,const std::vector<float>&holdout,
                int rate,gen37::Family family,double knownPickup,int maxEvaluations=70);

struct FEMFit {
 std::vector<gen37::Candidate> proposals;
 int evaluations=0;
 double ambiguityRatio=0;
 std::string error;
};
// 3D geometry generated by ShapeInverse37 plus small material/anisotropy search.
// Holds out a take from all model selection and refinement.
FEMFit fit3D(const std::vector<inverse36::Take>&takes,int rate,int maxEvaluations=50);
}
